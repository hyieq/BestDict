import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const env = { ...process.env, BESTDICT_TEST: '1', BESTDICT_TEST_SHORTCUT: 'Control+Alt+Shift+F11' };
delete env.ELECTRON_RUN_AS_NODE;
delete env.BESTDICT_LIBRARY;
const executablePath = process.env.BESTDICT_TEST_EXE;
const desktop = await electron.launch({ args: [...(executablePath ? [] : ['.']), '--force-device-scale-factor=1'], executablePath, cwd: root, env, timeout: 30000 });
const errors = [];
const captures = path.join(root, 'test-results');
await mkdir(captures, { recursive: true });
try {
  await desktop.evaluate(({ clipboard }) => { globalThis.__bestdictClipboard = { text: clipboard.readText(), html: clipboard.readHTML(), rtf: clipboard.readRTF(), image: clipboard.readImage() }; });
  const page = await desktop.firstWindow();
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.getByText('离线资源已就绪').waitFor();
  const captureAvailable = process.platform === 'win32';
  assert.equal(await page.evaluate(() => window.bestdict.getSettings().then(s => s.captureAvailable)), captureAvailable);
  assert.equal(await page.getByRole('button', { name: '截图翻译', exact: true }).count(), captureAvailable ? 1 : 0);
  assert.equal(await page.evaluate(() => window.bestdict.getSettings().then(s => s.translationEngine)), 'none');
  assert.equal(await page.evaluate(() => window.bestdict.getSettings().then(s => s.locale)), 'zh-CN');
  await assert.rejects(page.evaluate(() => window.bestdict.setSettings({ locale: 'invalid' })), /界面语言无效/);
  const slogans = ['词语之间，自有世界', '今天，想读懂什么？', '从一个词，抵达更多可能。', '安静陪伴', 'A LITTLE CLARITY', 'WORDS OPEN WORLDS'];
  for (const slogan of slogans) assert.equal((await page.locator('body').innerText()).includes(slogan), false);
  assert.equal(await desktop.evaluate(({ app }) => {
    const native = globalThis.__bestdictNative;
    return native.getTray().isDestroyed();
  }), false);
  const resources = await page.evaluate(() => window.bestdict.getResources());
  assert.equal(resources.argos.ready, false);
  assert.equal(resources.hy.ready, false);
  assert.equal(resources.progress, null, 'No resource download runs at startup.');
  await assert.rejects(page.evaluate(() => window.bestdict.setSettings({ translationEngine: 'argos' })), /请先下载/);
  await assert.rejects(page.evaluate(() => window.bestdict.setSettings({ translationEngine: 'hy' })), /AI 翻译/);
  await assert.rejects(page.evaluate(() => window.bestdict.translate('Hello world.', 'en-zh', 1)), /尚未开启/);
  const input = page.getByRole('textbox', { name: '输入单词或句子' });
  assert.equal(await input.evaluate(element => element === document.activeElement), true);
  await page.screenshot({ path: path.join(captures, 'welcome.png') });
  await input.fill('serendipity');
  await page.getByTestId('entry-word').filter({ hasText: 'serendipity' }).waitFor();
  assert.ok((await page.locator('.definition-list').innerText()).includes('发现'));
  await page.screenshot({ path: path.join(captures, 'dictionary.png') });
  await input.fill('ser');
  const candidates = page.getByRole('listbox', { name: '推荐词条' }).getByRole('option');
  await candidates.nth(4).waitFor();
  await input.press('ArrowDown');
  assert.equal(await candidates.nth(1).getAttribute('aria-selected'), 'true');
  await input.fill('zzzzqqqqxxxx');
  await input.fill('apple');
  await page.getByTestId('entry-word').filter({ hasText: 'apple' }).waitFor();
  await input.fill('苹果');
  await page.getByRole('option').filter({ hasText: 'apple' }).first().waitFor();
  await input.fill('in fact');
  await page.getByTestId('entry-word').filter({ hasText: 'in fact' }).waitFor();
  await page.getByRole('button', { name: '句子翻译', exact: true }).click();
  await input.fill('Please send me the report before Friday.');
  await page.getByTestId('translation-disabled').waitFor();
  assert.equal(await page.getByRole('alert').count(), 0);
  await page.getByRole('button', { name: '设置基础翻译', exact: true }).click();
  await page.getByTestId('engine-argos').getByText('未安装', { exact: true }).waitFor();
  assert.equal(await page.getByTestId('engine-hy').getByText('未安装', { exact: true }).count(), 1);
  assert.equal(await page.getByTestId('engine-argos').getByRole('button', { name: '导入模型包', exact: true }).isVisible(), false);
  await page.getByTestId('engine-argos').locator('summary').click();
  await page.getByTestId('engine-hy').locator('summary').click();
  const argos = JSON.parse(await readFile(path.join(root, 'resources/argos-model.json'), 'utf8'));
  const hy = JSON.parse(await readFile(path.join(root, 'resources/hy-model.json'), 'utf8'));
  await page.getByTestId('engine-argos').getByRole('button', { name: '复制下载链接', exact: true }).click();
  await page.getByTestId('engine-argos').getByRole('button', { name: '已复制两个链接', exact: true }).waitFor();
  assert.equal(await desktop.evaluate(({ clipboard }) => clipboard.readText()), argos.packages.map(p => p.url).join('\n'));
  await page.getByTestId('engine-hy').getByRole('button', { name: '复制下载链接', exact: true }).click();
  await page.getByTestId('engine-hy').getByRole('button', { name: '已复制', exact: true }).waitFor();
  assert.equal(await desktop.evaluate(({ clipboard }) => clipboard.readText()), hy.url);
  await assert.rejects(page.evaluate(() => window.bestdict.copyDownloadLinks('invalid')), /资源无效/);
  assert.equal(await desktop.evaluate(({ clipboard }) => clipboard.readText()), hy.url);
  assert.equal(await page.evaluate(() => window.bestdict.getResources().then(r => r.progress)), null, 'Copying a link must not trigger a model download.');
  await desktop.evaluate(({ dialog }) => {
    globalThis.__bestdictRestoreDialog = dialog.showOpenDialog;
    dialog.showOpenDialog = async (_window, options) => { if (!options.properties.includes('multiSelections')) throw new Error('Argos needs both files.'); return { canceled: true, filePaths: [] }; };
  });
  await page.getByTestId('engine-argos').getByRole('button', { name: '导入模型包', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('.save-button')?.disabled);
  await desktop.evaluate(({ dialog }) => { dialog.showOpenDialog = globalThis.__bestdictRestoreDialog; delete globalThis.__bestdictRestoreDialog; });
  assert.equal(await page.evaluate(() => window.bestdict.getResources().then(r => r.argos.ready)), false);
  await page.getByTestId('engine-hy').getByRole('button', { name: '复制下载链接', exact: true }).waitFor();
  await page.screenshot({ path: path.join(captures, 'optional-engines.png') });
  await page.getByRole('button', { name: '保存设置', exact: true }).click();
  await page.getByRole('button', { name: '查词', exact: true }).click();
  await input.fill('serendipity');
  await page.getByTestId('entry-word').filter({ hasText: 'serendipity' }).waitFor();
  await page.getByRole('button', { name: '设置', exact: true }).click();
  await page.getByRole('button', { name: '深色', exact: true }).click();
  await page.getByRole('button', { name: '保存设置', exact: true }).click();
  await page.locator('html[data-theme="dark"]').waitFor();
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
  await page.waitForTimeout(250);
  await page.screenshot({ path: path.join(captures, 'dark.png') });
  await page.getByRole('button', { name: '设置', exact: true }).click();
  await page.screenshot({ path: path.join(captures, 'settings.png') });
  await page.getByRole('combobox', { name: '界面语言' }).selectOption('en');
  await page.getByRole('button', { name: 'Save settings', exact: true }).click();
  await page.getByRole('button', { name: 'Settings', exact: true }).waitFor();
  assert.equal(await page.locator('html').getAttribute('lang'), 'en');
  assert.equal(await page.evaluate(() => window.bestdict.getSettings().then(s => s.locale)), 'en');
  const nativeLanguage = await desktop.evaluate(({ app }) => {
    const native = globalThis.__bestdictNative;
    const stored = native.readSettings();
    return { labels: native.getTrayMenu().items.map(item => item.label), storedLocale: stored.locale };
  });
  assert.equal(nativeLanguage.storedLocale, 'en');
  assert.deepEqual(nativeLanguage.labels, ['Open BestDict', 'Mini mode', 'Screenshot translation', 'Settings', '', 'Quit']);
  await page.getByRole('button', { name: 'Clear', exact: true }).click();
  await page.screenshot({ path: path.join(captures, 'english-welcome.png') });
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('tab', { name: 'Dictionaries', exact: true }).click();
  assert.ok((await page.getByRole('dialog').innerText()).includes('Japanese → Chinese'));
  assert.ok(!(await page.getByRole('dialog').innerText()).includes('中文版'));
  await page.getByRole('tab', { name: 'Translation engines', exact: true }).click();
  assert.ok((await page.getByRole('dialog').innerText()).includes('Download EN/ZH models'));
  await page.getByTestId('engine-argos').locator('summary').click();
  await page.getByTestId('engine-hy').locator('summary').click();
  assert.equal(await page.getByRole('button', { name: 'Copy download links', exact: true }).count(), 2);
  await page.getByRole('tab', { name: 'General', exact: true }).click();
  await page.screenshot({ path: path.join(captures, 'english-settings.png') });
  await page.getByRole('combobox', { name: 'Interface language' }).selectOption('zh-CN');
  await page.getByRole('button', { name: '保存设置', exact: true }).click();
  await page.getByRole('button', { name: '设置', exact: true }).click();
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(), 0);
  await desktop.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(780, 580));
  await input.fill('');
  await page.waitForTimeout(250);
  await page.screenshot({ path: path.join(captures, 'compact.png') });
  const compactBounds = await page.locator('.result-area').boundingBox();
  const exampleBounds = await page.locator('.sentence-example').boundingBox();
  assert.ok(exampleBounds.y + exampleBounds.height <= compactBounds.y + compactBounds.height, 'Compact welcome actions must fit within the result panel.');
  const registered = await desktop.evaluate(({ globalShortcut }) => globalShortcut.isRegistered('Control+Alt+Shift+F11'));
  assert.equal(registered, true);
  await page.keyboard.press('Escape');
  await page.waitForTimeout(200);
  assert.equal(await desktop.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isVisible()), false);
  await desktop.evaluate(({ app }) => {
    globalThis.__bestdictNative.getTray().emit('click');
  });
  await page.waitForTimeout(200);
  assert.equal(await input.evaluate(element => element === document.activeElement), true);
  assert.equal(await input.evaluate(element => element.selectionStart === 0 && element.selectionEnd === element.value.length), true);
  await page.getByRole('button', { name: '最小化', exact: true }).click();
  await page.waitForTimeout(200);
  assert.equal(await desktop.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isVisible()), false);
  await desktop.evaluate(({ app }) => {
    const native = globalThis.__bestdictNative;
    if (native.getTray().isDestroyed()) throw new Error('Tray must remain after minimize.');
    native.getTray().emit('double-click');
  });
  await page.waitForTimeout(200);
  assert.equal(await desktop.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isVisible()), true);
  await desktop.evaluate(({ app }) => {
    const native = globalThis.__bestdictNative;
    native.getTrayMenu().items.find(item => item.label === '设置').click();
  });
  await page.getByRole('dialog').waitFor();
  await page.keyboard.press('Escape');
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth || document.documentElement.scrollHeight > innerHeight);
  assert.equal(overflow, false);
  assert.deepEqual(errors, []);
  const result = { passed: true, packaged: !!executablePath, checks: ['official model link copying', 'copy does not download', 'native Argos picker cancellation', 'Chinese default', 'English and Chinese switch', 'locale saved to disk', 'native menu localization', 'removed slogans', 'tray lifetime', 'minimize to tray', 'tray single and double click restore', 'tray settings menu', 'words-only default', 'no auto download', 'uninstalled engine selection blocked', 'disabled IPC blocked', 'disabled sentence UI', 'offline word and phrase lookup', 'input focus', 'prefix suggestions', 'Chinese lookup', 'keyboard selection', 'stale input', 'theme settings', 'shortcut registered', 'hide and refocus', 'layout overflow', 'no renderer errors'] };
  await writeFile(path.join(captures, executablePath ? 'packaged-smoke.json' : 'smoke.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result));
} finally {
  await desktop.evaluate(({ clipboard }) => { if (globalThis.__bestdictClipboard) clipboard.write(globalThis.__bestdictClipboard); }).catch(() => {});
  await desktop.close();
}
