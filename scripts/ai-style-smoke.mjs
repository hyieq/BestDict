import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import path from 'node:path';
import { mkdir } from 'node:fs/promises';
const env = { ...process.env, BESTDICT_TEST: '1', BESTDICT_TEST_SHORTCUT: 'Control+Alt+Shift+F11' };
delete env.ELECTRON_RUN_AS_NODE;
const executablePath = process.env.BESTDICT_TEST_EXE;
const desktop = await electron.launch({ args: executablePath ? [] : ['.'], executablePath, env });
try {
  const page = await desktop.firstWindow();
  await page.getByText('离线资源已就绪').waitFor();
  await desktop.evaluate(() => {
    const { resources, hy } = globalThis.__bestdictNative.getServices();
    const status = resources.hyStatus.bind(resources);
    resources.hyStatus = () => ({ ...status(), ready: true });
    globalThis.__aiCalls = [];
    hy.translate = async (text, direction, hint, options) => {
      globalThis.__aiCalls.push({ text, direction, options });
      if (options.polishPrompt === 'fail') throw new Error('测试失败');
      return { text: options.polishPrompt ? '请周五前发我报告，谢谢！' : '请在星期五之前将报告发给我。', direction: 'en-zh', engine: 'Hy-MT2', cached: false };
    };
  });
  await page.reload();
  const style = page.getByRole('combobox', { name: '翻译风格', exact: true });
  await style.selectOption('professional');
  await page.waitForFunction(() => window.bestdict.getSettings().then(s => s.aiStyleId === 'professional'));
  await style.selectOption('__manage');
  const dialog = page.getByRole('dialog', { name: '管理翻译风格', exact: true });
  await dialog.getByRole('button', { name: '新增风格' }).click();
  await dialog.getByRole('textbox', { name: '风格名称 5', exact: true }).fill('新闻');
  await dialog.getByRole('textbox', { name: '风格提示词 5', exact: true }).fill('使用客观简洁的新闻表达，保留事实和数字。');
  await dialog.getByRole('button', { name: '保存风格' }).click();
  await dialog.waitFor({ state: 'hidden' });
  const saved = await page.evaluate(() => window.bestdict.getSettings());
  assert.equal(saved.aiStyles.length, 5);
  await style.selectOption(saved.aiStyles[4].id);
  await page.waitForFunction(id => window.bestdict.getSettings().then(s => s.aiStyleId === id), saved.aiStyles[4].id);
  await page.reload();
  await page.waitForFunction(id => document.querySelector('.ai-style-select')?.value === id, saved.aiStyles[4].id);
  await page.getByRole('textbox', { name: '输入单词或句子' }).fill('Please send me the report before Friday.');
  await page.getByRole('button', { name: 'AI 翻译', exact: true }).click();
  await page.getByTestId('ai-translation-result').waitFor();
  await page.getByRole('textbox', { name: '自定义润色提示词' }).fill('更像聊天，简短一点');
  await page.getByRole('button', { name: '润色并刷新' }).click();
  await page.getByTestId('ai-translation-result').filter({ hasText: '谢谢' }).waitFor();
  const calls = await desktop.evaluate(() => globalThis.__aiCalls);
  assert.equal(calls[0].options.styleName, '新闻');
  assert.equal(calls[1].options.previousText, '请在星期五之前将报告发给我。');
  assert.equal(calls[1].text, calls[0].text);
  await mkdir('test-results', { recursive: true });
  await page.screenshot({ path: path.resolve('test-results/ai-styles.png') });
  await style.selectOption('professional');
  await page.waitForFunction(() => document.querySelector('.ai-style-select')?.value === 'professional');
  await page.getByTestId('ai-translation-result').filter({ hasText: '星期五' }).waitFor();
  const changed = await desktop.evaluate(() => globalThis.__aiCalls.at(-1));
  assert.equal(changed.options.styleName, '专业');
  assert.equal(changed.options.forceRefresh, true);
  await page.getByRole('button', { name: '重新翻译', exact: true }).click();
  await page.getByRole('status').filter({ hasText: '模型返回了相同译文' }).waitFor();
  await page.getByRole('textbox', { name: '自定义润色提示词' }).fill('fail');
  await page.getByRole('button', { name: '润色并刷新' }).click();
  await page.getByRole('alert').filter({ hasText: '测试失败' }).waitFor();
  assert.match(await page.getByTestId('ai-translation-result').innerText(), /星期五/);
  await page.evaluate(() => window.bestdict.setSettings({ theme: 'dark' }));
  await page.reload();
  await page.locator('html[data-theme="dark"]').waitFor();
  await style.selectOption('__manage');
  await dialog.waitFor();
  await page.screenshot({ path: path.resolve('test-results/ai-style-manager.png') });
  await page.keyboard.press('Escape');
  await dialog.waitFor({ state: 'hidden' });
  assert.equal(await page.evaluate(() => document.visibilityState), 'visible');
  console.log('AI styles: persistence, custom presets, polishing, failure preservation and dialog keyboard checks passed.');
} finally { await desktop.close(); }
